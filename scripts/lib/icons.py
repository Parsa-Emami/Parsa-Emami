def nodes_to_svg(nodes: list[tuple[str, dict[str, str]]]) -> str:
    """Serialise icon nodes to raw SVG markup (no wrapper <svg>)."""
    parts = []
    for tag, attrs in nodes:
        attr = " ".join(f'{k}="{escape(str(v), quote=True)}"' for k, v in attrs.items())
        parts.append(f"<{tag} {attr}/>")
    return "".join(parts)


def stroke_icon(name: str) -> str:
    """Inner markup for a stroke icon (caller supplies the wrapper + stroke styles)."""
    if name == "linkedin":
        return nodes_to_svg(LINKEDIN_NODES)
    return nodes_to_svg(LUCIDE[name])


